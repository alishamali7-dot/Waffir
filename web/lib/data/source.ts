/**
 * مصدر البيانات — نقطة الوصل الوحيدة بين الواجهة والبيانات.
 *
 * ## لماذا واجهة ومصدران
 *
 * المصادقة ستُضاف لاحقًا (تسجيل دخول، حساب جديد، Apple، Google، حذف
 * حساب). وسياسات RLS على القاعدة تمنع قراءة أيّ صفّ بلا جلسة — فلو
 * ربطنا الواجهة بـSupabase مباشرة الآن لظهر التطبيق **فارغًا** ولا
 * يمكن الحكم على شي فيه.
 *
 * فالمصدر مجرّد دالة تُرجع `AppState`:
 *
 * - `sample`  — يعمل اليوم بلا حساب، لتقييم الواجهة والأرقام.
 * - `supabase` — جاهز، ويعمل في اللحظة التي توجد فيها جلسة.
 *
 * والاختيار في مكان واحد ([`index.ts`](index.ts))، فإضافة المصادقة
 * لا تلمس أيّ شاشة.
 */

import type { AppState } from '@shared/types';

export interface DataSource {
  readonly kind: 'sample' | 'supabase';
  /** هل البيانات المعروضة حقيقية؟ الواجهة تُعلم المستخدم إن لم تكن. */
  readonly isLive: boolean;
  loadState(): Promise<AppState>;
}
